const { chromium } = require("playwright");
const path = require("path");
const out = (n) => path.join(__dirname, n);
(async () => {
  const browser = await chromium.launch();
  const errors = [];
  const open = async (viewport) => {
    const page = await browser.newPage({ viewport, deviceScaleFactor: 1 });
    page.on("pageerror", (e) => errors.push(e.message));
    await page.goto("http://localhost:8090/", { waitUntil: "load" });
    await page.waitForTimeout(5000);
    return page;
  };
  const page = await open({ width: 1280, height: 1000 });
  await page.locator("#sidebar-panel-energy").first().click();
  await page.waitForTimeout(6000);
  const selector = page.locator("hui-energy-period-selector").first();
  const pickPreset = async (name) => { await selector.locator("ha-date-range-picker").first().click(); await page.waitForTimeout(800); await page.getByText(name, { exact: true }).first().click(); await page.waitForTimeout(4000); };
  const pickGranularity = async (name) => { await selector.locator("ha-dropdown ha-button[slot=trigger]").first().click(); await page.waitForTimeout(500); await selector.locator("ha-dropdown ha-dropdown-item", { hasText: name }).first().click(); await page.waitForTimeout(5000); };
  const overflowItem = async (name) => { await selector.locator("ha-dropdown ha-icon-button[slot=trigger]").first().click(); await page.waitForTimeout(500); await selector.locator("ha-dropdown-item", { hasText: name }).first().click(); await page.waitForTimeout(5000); };
  await pickPreset("Last 30 days");
  await pickGranularity("Weekly");
  await overflowItem("Compare data");
  await page.screenshot({ path: out("v-30d-weekly-compare.png") });
  await overflowItem("Compare to date");
  await page.screenshot({ path: out("v-30d-weekly-compare-to-date.png") });
  await pickPreset("This year");
  await pickGranularity("Yearly");
  await page.screenshot({ path: out("v-year-yearly-compare.png") });
  await pickGranularity("Monthly");
  await page.screenshot({ path: out("v-year-monthly-compare.png") });
  await page.close();
  const narrow = await open({ width: 400, height: 900 });
  await narrow.locator("ha-menu-button").first().click();
  await narrow.waitForTimeout(800);
  await narrow.locator("#sidebar-panel-energy").first().click();
  await narrow.waitForTimeout(6000);
  await narrow.screenshot({ path: out("v-narrow-1.png") });
  const nsel = narrow.locator("hui-energy-period-selector").first();
  await nsel.locator("ha-dropdown ha-icon-button[slot=trigger]").first().click();
  await narrow.waitForTimeout(600);
  await narrow.screenshot({ path: out("v-narrow-2-overflow.png") });
  await nsel.locator("ha-dropdown-item", { hasText: "Granularity" }).first().hover();
  await narrow.waitForTimeout(800);
  await narrow.screenshot({ path: out("v-narrow-3-submenu.png") });
  await narrow.close();
  console.log("errors:", JSON.stringify(errors).slice(0, 2000));
  await browser.close();
})();
